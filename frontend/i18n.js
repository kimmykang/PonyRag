function getCurrentLang() {
    try {
        const raw = localStorage.getItem('general_lang');
        if (raw) return JSON.parse(raw);
    } catch (e) {}
    return 'zh';
}

function setLang(lang) {
    localStorage.setItem('general_lang', JSON.stringify(lang));
    applyLang();
}

function t(key, vars) {
    const lang = getCurrentLang();
    const dict = LANGS[lang] || LANGS['zh'];
    let str = dict[key] !== undefined ? dict[key] : (LANGS['zh'][key] !== undefined ? LANGS['zh'][key] : key);
    if (vars) {
        Object.entries(vars).forEach(function(entry) {
            str = str.replace(new RegExp('\\{\\{' + entry[0] + '\\}\\}', 'g'), entry[1]);
        });
    }
    return str;
}

function applyLang() {
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        var attr = el.getAttribute('data-i18n-attr');
        var val = t(key);
        if (attr) {
            el.setAttribute(attr, val);
        } else {
            el.textContent = val;
        }
    });
    document.dispatchEvent(new CustomEvent('langchange', {
        detail: getCurrentLang()
    }));
}

window.t = t;
window.setLang = setLang;
window.applyLang = applyLang;
window.getCurrentLang = getCurrentLang;